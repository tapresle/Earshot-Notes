#!/usr/bin/env bash
# Writes the license notices for every third-party Rust crate and JavaScript
# package that ships in the app to src-tauri/resources/licenses/third-party-notices.txt.
# The app bundles that file next to the Earshot, needle, Whistle and llama.cpp licenses.
#
# Rust: cargo-about lists the normal dependencies of the app for the macOS
# Apple Silicon target (see scripts/notices/about.toml). Install it with
#   cargo install cargo-about --locked --features cli
# JavaScript: scripts/notices/js-notices.mjs lists the production dependencies
# in package-lock.json, reading license texts from node_modules (run `npm install` first).
#
# Usage:
#   ./scripts/generate-notices.sh          Regenerate the notices file.
#   ./scripts/generate-notices.sh --check  Fail if the committed file is out of date.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

OUT="src-tauri/resources/licenses/third-party-notices.txt"
CHECK=0
case "${1:-}" in
  "") ;;
  --check) CHECK=1 ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

if ! cargo about --version >/dev/null 2>&1; then
  echo "cargo-about isn't installed. Install it with:" >&2
  echo "  cargo install cargo-about --locked --features cli" >&2
  exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

cargo about generate \
  --locked \
  --manifest-path src-tauri/Cargo.toml \
  --config scripts/notices/about.toml \
  --output-file "$TMP/rust.txt" \
  scripts/notices/about.hbs

node scripts/notices/js-notices.mjs > "$TMP/js.txt"

{
  echo "Earshot third-party notices"
  echo "==========================="
  echo
  echo "Earshot includes the third-party software listed below. Each entry gives the"
  echo "license it's distributed under and that license's text with its copyright"
  echo "notices. The licenses for needle, Whistle and llama.cpp are in their own files"
  echo "next to this one."
  echo
  echo "This file is generated by scripts/generate-notices.sh. Don't edit it by hand."
  echo
  echo
  echo "Rust crates"
  echo "==========="
  echo
  cat "$TMP/rust.txt"
  echo
  echo
  echo "JavaScript packages"
  echo "==================="
  echo
  cat "$TMP/js.txt"
} > "$TMP/notices.txt"

if [[ "$CHECK" == 1 ]]; then
  if ! cmp -s "$TMP/notices.txt" "$OUT"; then
    echo "$OUT is out of date. Run ./scripts/generate-notices.sh and commit the result." >&2
    exit 1
  fi
  echo "$OUT is up to date."
else
  mv "$TMP/notices.txt" "$OUT"
  echo "Wrote $OUT"
fi
